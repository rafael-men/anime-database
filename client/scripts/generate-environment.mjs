import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const target = resolve(scriptDir, '../src/environments/environment.ts');

const normalizeOrigin = (value) => String(value).trim().replace(/\/+$/, '');

const apiBaseUrl = normalizeOrigin(process.env.API_BASE_URL ?? '');
const connectSrc = String(process.env.CSP_CONNECT_SRC ?? '')
  .split(/[\s,]+/)
  .map(normalizeOrigin)
  .filter(Boolean);

if (apiBaseUrl) {
  try {
    const parsed = new URL(apiBaseUrl);
    if (!['http:', 'https:'].includes(parsed.protocol)) {
      throw new Error(`unsupported protocol "${parsed.protocol}"`);
    }
  } catch (error) {
    console.error(
      `[generate-environment] Invalid API_BASE_URL "${apiBaseUrl}": ${error.message}`,
    );
    process.exit(1);
  }
}

const contents = `/**
 * AUTO-GENERATED by scripts/generate-environment.mjs — do not edit by hand.
 */
export interface AppEnvironment {
  /** Absolute origin of the API, e.g. https://api.example.com */
  apiBaseUrl: string;
  /** Extra origins allowed by the CSP connect-src directive. */
  cspConnectSrc: string[];
}

export const environment: AppEnvironment = {
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
  cspConnectSrc: ${JSON.stringify(connectSrc)},
};
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, contents, 'utf8');

console.log(
  `[generate-environment] apiBaseUrl=${
    apiBaseUrl || '(dev fallback: localhost:3000)'
  } cspConnectSrc=${
    connectSrc.length ? connectSrc.join(' ') : '(none)'
  }`,
);
